#!/usr/bin/env python3
"""Embed the local configuration page in flash; no filesystem upload is needed."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
page = (root / 'web/index.html').read_text()
assert ')panelhtml"' not in page
header = '#pragma once\n\n#include <Arduino.h>\n\n// Generated by tools/embed_web.py from web/index.html.\n'
header += 'static const char CONFIG_PAGE[] PROGMEM = R"panelhtml(' + page + ')panelhtml";\n'
destination = root / 'include/ConfigPage.h'
if not destination.exists() or destination.read_text() != header:
    destination.write_text(header)
print('Embedded web/index.html in include/ConfigPage.h')
